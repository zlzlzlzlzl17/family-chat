class MainActivity : ComponentActivity() {
    private var shareIntent by mutableStateOf<Intent?>(null)

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        NotificationCenter.ensureChannel(this)
        enableEdgeToEdge()
        shareIntent = intent.takeIf(::isShareIntent)
        setContent {
            val container = (application as FamilyChatApplication).container
            val shellViewModel: ShellViewModel = viewModel(
                factory = remember(application) { featureViewModelFactory { ShellViewModel(container) } }
            )
            val authViewModel: AuthViewModel = viewModel(
                factory = remember(application) { featureViewModelFactory { AuthViewModel(container) } }
            )
            if (!shellViewModel.uiState.isLoggedIn) {
                val authState = authViewModel.uiState
                ChatTheme(
                    displayMode = authState.displayMode,
                    dynamicColor = authState.dynamicColorsEnabled,
                    textSize = authState.textSize,
                ) {
                    if (shellViewModel.uiState.isRestoringSession || authState.isLoading) {
                        SessionRestoreScreen(authState)
                    } else {
                        LoginScreen(authViewModel, authState)
                    }
                }
            } else {
                val conversationViewModel: ConversationViewModel = viewModel(
                    factory = remember(application) { featureViewModelFactory { ConversationViewModel(container) } }
                )
                val callViewModel: CallViewModel = viewModel(
                    factory = remember(application) { featureViewModelFactory { CallViewModel(container) } }
                )
                val settingsViewModel: SettingsViewModel = viewModel(
                    factory = remember(application) { featureViewModelFactory { SettingsViewModel(container) } }
                )
                val settingsState = settingsViewModel.uiState
                ChatTheme(
                    displayMode = settingsState.displayMode,
                    dynamicColor = settingsState.dynamicColorsEnabled,
                    textSize = settingsState.textSize
                ) {
                    FamilyChatApp(
                        shellViewModel = shellViewModel,
                        authViewModel = authViewModel,
                        container = container,
                        conversationViewModel = conversationViewModel,
                        callViewModel = callViewModel,
                        settingsViewModel = settingsViewModel,
                        shareIntent = shareIntent,
                        onShareIntentConsumed = { shareIntent = null }
                    )
                }
            }
        }
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        setIntent(intent)
        shareIntent = intent.takeIf(::isShareIntent)
    }
}
